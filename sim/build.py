"""Rebuild every BITCH model file from sim/params.py.

    python -m sim.build            writes sim/out/ (MJCF, URDF, meshes, viewer data, preview images)
    python -m sim.build --no-png   skip the preview renders (no GPU / EGL needed)

Outputs:
    bitch.xml            MuJoCo model: physics, servos, cameras, sensors, keyframes (the master copy)
    bitch.urdf           same robot for PyBullet, ROS, Isaac Sim, Gazebo (primitives only, no mesh files)
    bitch.json           body tree + shapes for the web viewer and anything else that wants raw data
    meshes/bitch_<pose>.glb / .obj / .stl   the whole robot as one mesh, for Blender, CAD and 3D printing
    viewer.html          open in any browser: spin the model and drive the joints
    previews/*.png       renders from the front, side, three-quarter and BITCH's own eye camera
"""
import json, os, sys
if sys.platform.startswith('linux'):
    os.environ.setdefault('MUJOCO_GL', 'egl')       # headless rendering on Linux; macOS uses its own
from math import atan2, asin
import numpy as np
import mujoco
from . import params as P
from .model import mjcf

OUT = os.path.join(os.path.dirname(__file__), 'out')
GROUP_VISIBLE = (0, 1)          # geom groups that are part of the robot's look (4 = inside the box, hidden)


def load():
    xml = mjcf()
    return xml, mujoco.MjModel.from_xml_string(xml)


def rgba(m, g):
    mid = m.geom_matid[g]
    return [float(v) for v in (m.mat_rgba[mid] if mid >= 0 else m.geom_rgba[g])]


def quat_to_mat(q):
    R = np.zeros(9); mujoco.mju_quat2Mat(R, np.asarray(q, float)); return R.reshape(3, 3)


def rpy(R):
    """URDF fixed-axis roll, pitch, yaw."""
    p = asin(max(-1, min(1, -R[2, 0])))
    if abs(R[2, 0]) < 0.99999:
        return atan2(R[2, 1], R[2, 2]), p, atan2(R[1, 0], R[0, 0])
    return atan2(-R[1, 2], R[1, 1]), p, 0.0


def _f(v):
    return ' '.join(f'{x:.6g}' for x in v)


# ---------------------------------------------------------------- URDF
def urdf(m):
    names = [m.body(b).name for b in range(m.nbody)]
    names[0] = 'box'
    mats = {}
    out = ['<?xml version="1.0"?>', '<!-- Generated by sim/build.py from sim/params.py. -->', '<robot name="bitch">']

    def geometry(g):
        t, s = m.geom_type[g], m.geom_size[g]
        if t == mujoco.mjtGeom.mjGEOM_BOX: return f'<box size="{_f(2 * s)}"/>'
        if t == mujoco.mjtGeom.mjGEOM_CYLINDER: return f'<cylinder radius="{s[0]:.6g}" length="{2 * s[1]:.6g}"/>'
        if t == mujoco.mjtGeom.mjGEOM_SPHERE: return f'<sphere radius="{s[0]:.6g}"/>'
        if t == mujoco.mjtGeom.mjGEOM_ELLIPSOID: return f'<cylinder radius="{max(s[1], s[2]):.6g}" length="{2 * s[0]:.6g}"/>'  # URDF has no ellipsoid
        return None

    for b in range(m.nbody):
        out.append(f'  <link name="{names[b]}">')
        if not b:   # the box with the Pi inside; fixed in place, mass only matters if you un-fix it
            out.append(f'    <inertial><origin xyz="0 0 {P.BOX_HEIGHT / 2000:.4g}"/><mass value="0.25"/>'
                       '<inertia ixx="1e-3" ixy="0" ixz="0" iyy="1e-3" iyz="0" izz="1e-3"/></inertial>')
        else:
            R = quat_to_mat(m.body_iquat[b]); I = R @ np.diag(m.body_inertia[b]) @ R.T
            out += [f'    <inertial><origin xyz="{_f(m.body_ipos[b])}"/><mass value="{m.body_mass[b]:.6g}"/>',
                    f'      <inertia ixx="{I[0,0]:.4e}" ixy="{I[0,1]:.4e}" ixz="{I[0,2]:.4e}" iyy="{I[1,1]:.4e}" iyz="{I[1,2]:.4e}" izz="{I[2,2]:.4e}"/></inertial>']
        for g in range(m.ngeom):
            if m.geom_bodyid[g] != b or m.geom_group[g] not in GROUP_VISIBLE: continue
            geo = geometry(g)
            if geo is None: continue                                     # the desk plane
            o = f'<origin xyz="{_f(m.geom_pos[g])}" rpy="{_f(rpy(quat_to_mat(m.geom_quat[g])))}"/>'
            c = rgba(m, g); key = 'c_' + '_'.join(f'{int(x * 100)}' for x in c); mats[key] = c
            out.append(f'    <visual name="{m.geom(g).name}">{o}<geometry>{geo}</geometry><material name="{key}"/></visual>')
            if m.geom_contype[g]:
                out.append(f'    <collision name="{m.geom(g).name}">{o}<geometry>{geo}</geometry></collision>')
        out.append('  </link>')
    for j in range(m.njnt):
        b = m.jnt_bodyid[j]; p = m.body_parentid[b]
        lo, hi = m.jnt_range[j]
        out += [f'  <joint name="{m.joint(j).name}" type="revolute">',
                f'    <parent link="{names[p]}"/><child link="{names[b]}"/>',
                f'    <origin xyz="{_f(m.body_pos[b])}" rpy="{_f(rpy(quat_to_mat(m.body_quat[b])))}"/>',
                f'    <axis xyz="{_f(m.jnt_axis[j])}"/>',
                f'    <limit lower="{lo:.5g}" upper="{hi:.5g}" effort="{P.SERVO_STALL_TORQUE}" velocity="{(np.pi / 3) / P.SERVO_SPEED:.4g}"/>',
                f'    <dynamics damping="{m.dof_damping[j]:.4g}" friction="{m.dof_frictionloss[j]:.4g}"/>',
                '  </joint>']
    out += [f'  <material name="{k}"><color rgba="{_f(v)}"/></material>' for k, v in mats.items()]
    out.append('</robot>\n')
    return '\n'.join(out)


# ---------------------------------------------------------------- viewer / raw data
def as_json(m):
    kinds = {int(mujoco.mjtGeom.mjGEOM_BOX): 'box', int(mujoco.mjtGeom.mjGEOM_CYLINDER): 'cylinder',
             int(mujoco.mjtGeom.mjGEOM_SPHERE): 'sphere', int(mujoco.mjtGeom.mjGEOM_ELLIPSOID): 'ellipsoid'}
    bodies = []
    for b in range(m.nbody):
        jn = [j for j in range(m.njnt) if m.jnt_bodyid[j] == b]
        body = dict(name=m.body(b).name or 'world', parent=int(m.body_parentid[b]) if b else None,
                    pos=m.body_pos[b].round(6).tolist(), quat=m.body_quat[b].round(6).tolist(), geoms=[])
        if jn:
            j = jn[0]; i = list(P.NAMES).index(m.joint(j).name)
            body['joint'] = dict(name=m.joint(j).name, axis=m.jnt_axis[j].tolist(), deg_per_unit=P.DEG_PER_UNIT[i],
                                 reach=list(P.REACH[i]), safe=[P.SAFE_LO[i], P.SAFE_HI[i]], rest=P.REST[i])
        for g in range(m.ngeom):
            if m.geom_bodyid[g] != b or int(m.geom_type[g]) not in kinds: continue
            body['geoms'].append(dict(name=m.geom(g).name, type=kinds[int(m.geom_type[g])], size=m.geom_size[g].round(6).tolist(),
                                      pos=m.geom_pos[g].round(6).tolist(), quat=m.geom_quat[g].round(6).tolist(),
                                      rgba=[round(x, 3) for x in rgba(m, g)], group=int(m.geom_group[g]),
                                      mat=m.mat(m.geom_matid[g]).name if m.geom_matid[g] >= 0 else ''))
        bodies.append(body)
    return dict(name='BITCH', units='metres, radians; joint values in desk.py units (-1..1)', frame='x forward, y left, z up',
                lid_height=P.BOX_HEIGHT / 1000, bodies=bodies,
                poses=dict(rest=list(P.REST), upright=[0, 0, 0, 0]))


# ---------------------------------------------------------------- meshes
def meshes(m, pose, path_base):
    import trimesh
    d = mujoco.MjData(m); d.qpos[:] = P.to_rad(pose); mujoco.mj_forward(m, d)
    parts = []
    for g in range(m.ngeom):
        if m.geom_group[g] not in GROUP_VISIBLE: continue
        t, s = m.geom_type[g], m.geom_size[g]
        if t == mujoco.mjtGeom.mjGEOM_BOX: mesh = trimesh.creation.box(extents=2 * s)
        elif t == mujoco.mjtGeom.mjGEOM_CYLINDER: mesh = trimesh.creation.cylinder(radius=s[0], height=2 * s[1], sections=40)
        elif t == mujoco.mjtGeom.mjGEOM_SPHERE: mesh = trimesh.creation.icosphere(subdivisions=2, radius=s[0])
        elif t == mujoco.mjtGeom.mjGEOM_ELLIPSOID:
            mesh = trimesh.creation.icosphere(subdivisions=3, radius=1.0); mesh.apply_scale(s)
        else: continue
        T = np.eye(4); T[:3, :3] = d.geom_xmat[g].reshape(3, 3); T[:3, 3] = d.geom_xpos[g]
        mesh.apply_transform(T)
        mesh.visual.face_colors = (np.array(rgba(m, g)) * 255).astype(np.uint8)
        mesh.metadata['name'] = m.geom(g).name
        parts.append(mesh)
    scene = trimesh.Scene()
    for p in parts: scene.add_geometry(p, node_name=p.metadata['name'], geom_name=p.metadata['name'])
    scene.export(path_base + '.glb')
    whole = trimesh.util.concatenate(parts)
    whole.export(path_base + '.stl')
    whole.export(path_base + '.obj')


# ---------------------------------------------------------------- previews
def previews(m, folder):
    from PIL import Image
    d = mujoco.MjData(m); r = mujoco.Renderer(m, 900, 1200)
    shots = [('rest', 'front'), ('rest', 'side'), ('rest', 'three_quarter'), ('upright', 'side'),
             ('curious', 'three_quarter'), ('bedtime', 'side'), ('rest', 'eye')]
    for key, cam in shots:
        mujoco.mj_resetDataKeyframe(m, d, m.key(key).id); mujoco.mj_forward(m, d)
        r.update_scene(d, camera=cam)
        Image.fromarray(r.render()).save(os.path.join(folder, f'{key}_{cam}.png'))
    r.close()


def main(argv=()):
    xml, m = load()
    os.makedirs(os.path.join(OUT, 'meshes'), exist_ok=True)
    open(os.path.join(OUT, 'bitch.xml'), 'w').write(xml)
    open(os.path.join(OUT, 'bitch.urdf'), 'w').write(urdf(m))
    json.dump(as_json(m), open(os.path.join(OUT, 'bitch.json'), 'w'), separators=(',', ':'))
    tpl = open(os.path.join(os.path.dirname(__file__), 'viewer', 'template.html')).read()
    data = json.dumps(as_json(m), separators=(',', ':')).replace('</', '<\\/')
    open(os.path.join(OUT, 'viewer.html'), 'w').write(tpl.replace('/*MODEL*/null/*END*/', data))
    for name, pose in (('rest', P.REST), ('upright', (0, 0, 0, 0))):
        meshes(m, pose, os.path.join(OUT, 'meshes', f'bitch_{name}'))
    if '--no-png' not in argv:
        os.makedirs(os.path.join(OUT, 'previews'), exist_ok=True)
        try: previews(m, os.path.join(OUT, 'previews'))
        except Exception as e: print('previews skipped:', e)
    print(f'BITCH model rebuilt in {OUT}: {m.nbody - 1} moving bodies, {m.ngeom} shapes, '
          f'{sum(m.body_mass) * 1000:.0f} g moving mass')


if __name__ == '__main__':
    main(sys.argv[1:])
